import Foundation

/// FBX export, ASCII flavor (version 7.4): one mesh model with normals and UVs, plus a
/// material and texture reference when the source is textured. Static geometry only —
/// there is no skeleton or animation yet (the roadmap's rigging items are not built).
enum FBXExporter {
    /// `textureName` is the PNG file written next to the FBX (relative reference).
    static func encode(_ mesh: MeshExporter.MeshData, name: String, textureName: String?) -> Data {
        let hasUV = mesh.uvs != nil
        var s = "; FBX 7.4.0 project file\n; Generated by GrizzyModlr\n\n"
        s += "FBXHeaderExtension:  {\n\tFBXHeaderVersion: 1003\n\tFBXVersion: 7400\n\tCreator: \"GrizzyModlr\"\n}\n\n"
        s += "GlobalSettings:  {\n\tVersion: 1000\n\tProperties70:  {\n"
        s += "\t\tP: \"UpAxis\", \"int\", \"Integer\", \"\",1\n\t\tP: \"UpAxisSign\", \"int\", \"Integer\", \"\",1\n"
        s += "\t\tP: \"FrontAxis\", \"int\", \"Integer\", \"\",2\n\t\tP: \"FrontAxisSign\", \"int\", \"Integer\", \"\",1\n"
        s += "\t\tP: \"CoordAxis\", \"int\", \"Integer\", \"\",0\n\t\tP: \"CoordAxisSign\", \"int\", \"Integer\", \"\",1\n"
        s += "\t\tP: \"UnitScaleFactor\", \"double\", \"Number\", \"\",1\n\t}\n}\n\n"
        s += "Definitions:  {\n\tVersion: 100\n\tCount: 4\n"
        s += "\tObjectType: \"Model\" {\n\t\tCount: 1\n\t}\n\tObjectType: \"Geometry\" {\n\t\tCount: 1\n\t}\n"
        s += "\tObjectType: \"Material\" {\n\t\tCount: 1\n\t}\n\tObjectType: \"Texture\" {\n\t\tCount: \(textureName == nil ? 0 : 1)\n\t}\n}\n\n"

        let geoID = 1_000_001, modelID = 1_000_002, matID = 1_000_003, texID = 1_000_004
        s += "Objects:  {\n"
        s += "\tGeometry: \(geoID), \"Geometry::\(name)\", \"Mesh\" {\n"
        s += "\t\tVertices: *\(mesh.vertCount * 3) {\n\t\t\ta: " + list(mesh.verts.map { "\($0)" }) + "\n\t\t}\n"
        // Polygon vertex indices: the last index of each polygon is stored as ~i.
        var poly: [String] = []
        poly.reserveCapacity(mesh.faceCount * 3)
        for f in 0..<mesh.faceCount {
            poly.append("\(mesh.indices[f * 3])"); poly.append("\(mesh.indices[f * 3 + 1])")
            poly.append("\(-Int(mesh.indices[f * 3 + 2]) - 1)")
        }
        s += "\t\tPolygonVertexIndex: *\(poly.count) {\n\t\t\ta: " + list(poly) + "\n\t\t}\n"
        s += "\t\tGeometryVersion: 124\n"
        s += "\t\tLayerElementNormal: 0 {\n\t\t\tVersion: 101\n\t\t\tName: \"\"\n\t\t\tMappingInformationType: \"ByVertice\"\n"
        s += "\t\t\tReferenceInformationType: \"Direct\"\n\t\t\tNormals: *\(mesh.vertCount * 3) {\n\t\t\t\ta: "
        s += list(mesh.normals.map { "\($0)" }) + "\n\t\t\t}\n\t\t}\n"
        if hasUV, let uv = mesh.uvs {
            // Our UVs have a top-left origin; FBX's is bottom-left.
            var flipped: [String] = []
            flipped.reserveCapacity(uv.count)
            for i in 0..<mesh.vertCount { flipped.append("\(uv[i * 2])"); flipped.append("\(1 - uv[i * 2 + 1])") }
            s += "\t\tLayerElementUV: 0 {\n\t\t\tVersion: 101\n\t\t\tName: \"UVMap\"\n\t\t\tMappingInformationType: \"ByVertice\"\n"
            s += "\t\t\tReferenceInformationType: \"Direct\"\n\t\t\tUV: *\(uv.count) {\n\t\t\t\ta: " + list(flipped) + "\n\t\t\t}\n\t\t}\n"
        }
        s += "\t\tLayerElementMaterial: 0 {\n\t\t\tVersion: 101\n\t\t\tName: \"\"\n\t\t\tMappingInformationType: \"AllSame\"\n"
        s += "\t\t\tReferenceInformationType: \"IndexToDirect\"\n\t\t\tMaterials: *1 {\n\t\t\t\ta: 0\n\t\t\t}\n\t\t}\n"
        s += "\t\tLayer: 0 {\n\t\t\tVersion: 100\n"
        s += "\t\t\tLayerElement:  {\n\t\t\t\tType: \"LayerElementNormal\"\n\t\t\t\tTypedIndex: 0\n\t\t\t}\n"
        if hasUV { s += "\t\t\tLayerElement:  {\n\t\t\t\tType: \"LayerElementUV\"\n\t\t\t\tTypedIndex: 0\n\t\t\t}\n" }
        s += "\t\t\tLayerElement:  {\n\t\t\t\tType: \"LayerElementMaterial\"\n\t\t\t\tTypedIndex: 0\n\t\t\t}\n\t\t}\n\t}\n"
        s += "\tModel: \(modelID), \"Model::\(name)\", \"Mesh\" {\n\t\tVersion: 232\n\t\tProperties70:  {\n"
        s += "\t\t\tP: \"DefaultAttributeIndex\", \"int\", \"Integer\", \"\",0\n\t\t}\n\t\tShading: T\n\t\tCulling: \"CullingOff\"\n\t}\n"
        s += "\tMaterial: \(matID), \"Material::material0\", \"\" {\n\t\tVersion: 102\n\t\tShadingModel: \"phong\"\n\t\tMultiLayer: 0\n"
        s += "\t\tProperties70:  {\n\t\t\tP: \"DiffuseColor\", \"Color\", \"\", \"A\",0.8,0.8,0.8\n\t\t}\n\t}\n"
        if let textureName {
            s += "\tTexture: \(texID), \"Texture::albedo\", \"\" {\n\t\tType: \"TextureVideoClip\"\n\t\tVersion: 202\n"
            s += "\t\tTextureName: \"Texture::albedo\"\n\t\tFileName: \"\(textureName)\"\n\t\tRelativeFilename: \"\(textureName)\"\n\t}\n"
        }
        s += "}\n\n"
        s += "Connections:  {\n\tC: \"OO\",\(modelID),0\n\tC: \"OO\",\(geoID),\(modelID)\n\tC: \"OO\",\(matID),\(modelID)\n"
        if textureName != nil { s += "\tC: \"OP\",\(texID),\(matID), \"DiffuseColor\"\n" }
        s += "}\n"
        return Data(s.utf8)
    }

    private static func list(_ items: [String]) -> String { items.joined(separator: ",") }
}
